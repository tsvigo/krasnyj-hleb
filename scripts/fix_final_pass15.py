#!/usr/bin/env python3
"""Проход 15: финал — кавычки, многоточия, пробелы, пропущенные ». Только проект."""
from pathlib import Path
import re

P = Path("/home/v/projects/Красный хлеб/2015.52429.Red-Bread_djvu.ru.txt")
t = P.read_text(encoding="utf-8")

PAIRS = [
    # прямые кавычки -> «»
    ('"замужем по церкви",', '«замужем по церкви»,', 1),
    ('слово "колхоз" вызывало', 'слово «колхоз» вызывало', 1),
    ('означает "кулак", и', 'означает «кулак», и', 1),
    ('называют "мощным хозяйством",', 'называют «мощным хозяйством»,', 1),
    ('"принесет ему дополнительную прибыль".', '«принесет ему дополнительную прибыль».', 1),
    ('"декулачили", и я страдаю', '«декулачили», и я страдаю', 1),
    ('жизни "…", едва ли', 'жизни «…», едва ли', 1),
    ('"Только чтобы собрать всё снова",', '«Только чтобы собрать всё снова»,', 1),
    # ASCII-одиночные
    ("'лишнюю'", "‘лишнюю’", 1),
    ("'декулацированного'", "«декулацированного»", 1),
    ("'Всё, что ты слышишь, это то, что они строят, строят,'", "‘Всё, что ты слышишь, это то, что они строят, строят,’", 1),
    ("'И зачем, зачем им всё это нужно?", "‘И зачем, зачем им всё это нужно?", 1),
    ("ни покоя, ни жизни, ничего…'", "ни покоя, ни жизни, ничего…’", 1),
    ("от дома, а…'", "от дома, а…’", 1),
    ("‘Ах, какая наказань>е'\\ ", "‘Ах, какое наказанье!” ", 1),
    ("• А 'пшеничный хлеб.", "• А ‘пшеничный хлеб’.", 1),
    # пропущенные закрывающие
    ("чтобы уехать в это ужасное место – Котлас.",
     "чтобы уехать в это ужасное место – Котлас.»", 1),
    ("Вот вам ситуация!", "Вот вам ситуация!»", 1),
    ("и это беспокоит тебя.", "и это беспокоит тебя.»", 1),
    ("плюются на них - и ничего не происходит.", "плюются на них - и ничего не происходит.»", 1),
    ("и сказал: «В колхозе есть новый порядок, и нет необходимости в священниках, религии или крестинах».",
     "и сказал: „В колхозе есть новый порядок, и нет необходимости в священниках, религии или крестинах“.", 1),
    ("Теперь мы строим жилье для двухсот маток.",
     "Теперь мы строим жилье для двухсот маток.»", 1),
    # раскулачивание: пропущенные формы
    ("декулачизации", "раскулачивания", 1),
    ("декулачили", "раскулачили", 5),
    ("декулацированного", "раскулаченного", 1),
]

errors, n = [], 0
for old, new, exp in PAIRS:
    if exp == 0:
        continue
    c = t.count(old)
    if c != exp:
        errors.append(f"ОЖИДАЛОСЬ {exp}, НАЙДЕНО {c}: {old[:70]!r}")
        continue
    t = t.replace(old, new)
    n += c
if errors:
    print("ОШИБКИ (файл НЕ записан):")
    for e in errors:
        print(" -", e)
    raise SystemExit(1)

# многоточия: сначала ...., потом ...
c4 = t.count("....")
assert c4 == 11, c4
t = t.replace("....", "….")
c3 = t.count("...")
t = t.replace("...", "…")
print(f"многоточия: ....->{c4}, ...->{c3}")

# пробелы: хвосты, ведущие, двойные
lines = t.splitlines()
trail = sum(1 for l in lines if l != l.rstrip())
lead = sum(1 for l in lines if l != l.lstrip())
t = "\n".join(re.sub(r" {2,}", " ", l.strip()) for l in lines)
dbl = len(re.findall(r" {2,}", "\n".join(lines)))
print(f"пробелы: хвосты={trail}, ведущие={lead}, двойные={dbl}")

P.write_text(t, encoding="utf-8")
print(f"OK: {n} замен + типографика")
