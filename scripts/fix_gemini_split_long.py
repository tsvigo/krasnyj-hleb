#!/usr/bin/env python3
"""Разбивка 5 длинных предложений в Gemini-переводе (подтверждено пользователем)."""
from pathlib import Path

P = Path("/home/v/projects/Красный хлеб/gemini/RED-BREAD-gemini-ru.txt")

SPLITS = [
    # (фрагмент до замены, замена) — каждая ровно 1 вхождение
    ("не изменилась; всё казалось таким же",
     "не изменилась. Всё казалось таким же"),
    ("чтобы убедиться, что внутри она не пустая; они никогда не покупали",
     "чтобы убедиться, что внутри она не пустая. Они никогда не покупали"),
    ("были частью сценического оформления, и в программу которого входили танец урожая, угольный танец и нефтяной танец,",
     "были частью сценического оформления. В программу входили танец урожая, угольный танец и нефтяной танец,"),
    ("его тёплое дыхание на своём лице, была одна группа людей",
     "его тёплое дыхание на своём лице. Была одна группа людей"),
    ("хотя бы не умрут с голоду в пути на север, и знаешь, что случилось, знаешь?",
     "хотя бы не умрут с голоду в пути на север. И знаешь, что случилось, знаешь?"),
    ("своими личными бедами — если когда-нибудь увидишь больших людей в Москве, Пскова или Сталина, пожалуйста, скажи им,",
     "своими личными бедами. Если когда-нибудь увидишь больших людей в Москве, Пскова или Сталина, пожалуйста, скажи им,"),
    ("одной коровы и одной свиньи, да я, может, даже обойдусь без лошади,",
     "одной коровы и одной свиньи. Да я, может, даже обойдусь без лошади,"),
]


def main():
    t = P.read_text(encoding="utf-8")
    errors = []
    for old, new in SPLITS:
        c = t.count(old)
        if c != 1:
            errors.append(f"вхождений {c} (ожидалось 1): {old[:60]}...")
            continue
        t = t.replace(old, new)
    if errors:
        print("ОШИБКИ (файл НЕ записан):")
        for e in errors:
            print(" -", e)
        raise SystemExit(1)
    P.write_text(t, encoding="utf-8")
    print(f"OK: {len(SPLITS)} разбивок записано")


if __name__ == "__main__":
    main()
