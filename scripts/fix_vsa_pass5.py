#!/usr/bin/env python3
"""Проход 5: вся-группа + пропуски. Только папка проекта."""
from pathlib import Path

P = Path("/home/v/projects/Красный хлеб/2015.52429.Red-Bread_djvu.ru.txt")
t = P.read_text(encoding="utf-8")

PAIRS = [
    # пропущенные всё (не попали в пул, проверены глазами)
    ("мы продали все за еду, за хлеб",
     "мы продали всё за еду, за хлеб", 1),
    ("сжимая все на своём пути",
     "сжимая всё на своём пути", 1),
    ("продолжал с все большей страстью",
     "продолжал со всё большей страстью", 1),
    ("Они бы мне все равно не подошли",
     "Они бы мне всё равно не подошли", 1),
    # вся-группа (переопределяют dec_b2/b3: там vse=no-op, правильно — вся/весь)
    ("мужчины, которые все зиму готовились",
     "мужчины, которые всю зиму готовились", 1),
    ("был так занят все день венчанием людей",
     "был так занят весь день венчанием людей", 1),
    ("и все картошки, которую хотим",
     "и всю картошку, которую хотим", 1),
    # masculine: весь овёс
    ("и все овса и неубранное зерно",
     "и весь овёс и неубранное зерно", 1),
]

errors, n = [], 0
for old, new, exp in PAIRS:
    c = t.count(old)
    if c != exp:
        errors.append(f"ОЖИДАЛОСЬ {exp}, НАЙДЕНО {c}: {old[:70]!r}")
        continue
    t = t.replace(old, new)
    n += 1
if errors:
    print("ОШИБКИ (файл НЕ записан):")
    for e in errors:
        print(" -", e)
    raise SystemExit(1)
P.write_text(t, encoding="utf-8")
print(f"OK: {n} замен")
