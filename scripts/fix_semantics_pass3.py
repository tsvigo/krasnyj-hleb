#!/usr/bin/env python3
"""Проход 3: смысловая вычитка. Только папка проекта."""
from pathlib import Path

P = Path("/home/v/projects/Красный хлеб/2015.52429.Red-Bread_djvu.ru.txt")

PAIRS = [
    # склейка оборванного хвоста: конец 1966 + 1968
    ("умоляя мать закрыть шторы, чтобы она больше его не видела.\n\nУлицу, а все время ее легкие становились хуже, и совсем недавно она умерла.",
     "умоляя мать закрыть шторы, чтобы больше не видеть улицы, а всё время её лёгкие становились хуже, и совсем недавно она умерла.", 1),
    # бегущий колонтитул-глюк
    ("ХЛЕБ СЕРДЦА", "КРАСНЫЙ ХЛЕБ", 1),
    # herdsman, а не pastor
    ("ХОЗЯИН-ПАСТОР", "ХОЗЯИН-ПАСТУХ", 2),
    # the return of the native = возвращение уроженца
    ("ВОЗВРАЩЕНИЕ РОДЯЩАГОСЯ", "ВОЗВРАЩЕНИЕ УРОЖЕНЦА", 2),
    ("ВОЗВРАЩЕНИЕ РОДЯЧКИ", "ВОЗВРАЩЕНИЕ УРОЖЕНЦА", 2),
    # украинизм
    ("Колгоспные бригады", "Колхозные бригады", 1),
    # унификация заголовка главы
    ("РАЗДЕЛ IV", "ГЛАВА IV", 1),
]

def main():
    t = P.read_text(encoding="utf-8")
    errors = []
    applied = 0
    for old, new, exp in PAIRS:
        c = t.count(old)
        if c != exp:
            errors.append(f"ОЖИДАЛОСЬ {exp}, НАЙДЕНО {c}: {old[:80]!r}")
            continue
        t = t.replace(old, new)
        applied += 1
    if errors:
        print("ОШИБКИ (файл НЕ записан):")
        for e in errors:
            print(" -", e)
        raise SystemExit(1)
    P.write_text(t, encoding="utf-8")
    print(f"OK: применено {applied} замен")

if __name__ == "__main__":
    main()
