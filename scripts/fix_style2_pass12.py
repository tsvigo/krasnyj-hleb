#!/usr/bin/env python3
"""Проход 12: раздел 3 — плеоназмы и сочетаемость. Только папка проекта."""
from pathlib import Path

P = Path("/home/v/projects/Красный хлеб/2015.52429.Red-Bread_djvu.ru.txt")
t = P.read_text(encoding="utf-8")

PAIRS = [
    ("и всегда тяжело забиты навозом",
     "и вечно густо покрыты навозом", 1),
    ("тот, кто привык делать все свои собственные планы",
     "тот, кто привык строить все свои планы", 1),
    ("пусть правительство найдет свои собственные способы управлять этим делом",
     "пусть правительство найдёт свои способы управлять этим делом", 1),
    ("Они также могут обрабатывать свои собственные сады и фруктовые деревья",
     "Они также могут обрабатывать свои сады и фруктовые деревья", 1),
    ("статьи, которые рассказывают свою собственную историю",
     "статьи, которые рассказывают свою историю", 1),
    ("даст вам коммунистам свою собственную медицину",
     "даст вам, коммунистам, вашего собственного лекарства", 1),
]

errors, n = [], 0
for old, new, exp in PAIRS:
    c = t.count(old)
    if c != exp:
        errors.append(f"ОЖИДАЛОСЬ {exp}, НАЙДЕНО {c}: {old[:70]!r}")
        continue
    t = t.replace(old, new)
    n += 1
if errors:
    print("ОШИБКИ (файл НЕ записан):")
    for e in errors:
        print(" -", e)
    raise SystemExit(1)
P.write_text(t, encoding="utf-8")
print(f"OK: {n} замен")
