#!/usr/bin/env python3
"""Проход по методологии над Gemini-переводом: термины, грамматика, стиль, кавычки, многоточия."""
from pathlib import Path

P = Path("/home/v/projects/Красный хлеб/gemini/RED-BREAD-gemini-ru.txt")
t = P.read_text(encoding="utf-8")

PAIRS = [
    # 1. Лексика: единообразие с главным файлом (решение: Шатокуа/шатоквский)
    ("чаутокуанские", "шатоквские", 1),
    ("Чаутокуа", "Шатокуа", 11),
    # 1. Имя: как в главном файле (Терухин)
    ("Абрам Терен", "Абрам Терухин", 1),
    # 2. Грамматика: двойное «не» (по смыслу оригинала и главного файла)
    ("И им не не хватает социальной цели?", "И им не хочется социальной цели?", 1),
    # 3. Стиль: калька «является + отгл.»
    ("теперь является разрушающимся зданием", "теперь это разрушающееся здание", 1),
    # 5. Формат: две пропущенные открывающие кавычки прямой речи
    ("с обидой. — Мы никого не убивали", "с обидой. — «Мы никого не убивали", 1),
    ("из подруг. — Мы бы все поехали", "из подруг. — «Мы бы все поехали", 1),
]

errors, n = [], 0
for old, new, exp in PAIRS:
    c = t.count(old)
    if c != exp:
        errors.append(f"ОЖИДАЛОСЬ {exp}, НАЙДЕНО {c}: {old[:60]!r}")
        continue
    t = t.replace(old, new)
    n += c

# 7. Многоточия: ... → … (единообразие с главным файлом: там … ×252, ... ×0)
dots = t.count("...")
t = t.replace("...", "…")
n += dots
# после замены не должно остаться «……» или «….»
assert "……" not in t, "получилось двойное многоточие"
assert t.count("...") == 0

if errors:
    print("ОШИБКИ (файл НЕ записан):")
    for e in errors:
        print(" -", e)
    raise SystemExit(1)
P.write_text(t, encoding="utf-8")
print(f"OK: {n} замен (из них многоточий: {dots})")
