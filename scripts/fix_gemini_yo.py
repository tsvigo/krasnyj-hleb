def main():
    t = P.read_text(encoding="utf-8")
    errors, total = [], 0
    for old, (new, exp) in WORDS.items():
        pat = re.compile(r"\b" + re.escape(old) + r"\b")
        c = len(pat.findall(t))
        if c != exp:
            errors.append(f"ОЖИДАЛОСЬ {exp}, НАЙДЕНО {c}: {old!r}")
            continue
        t = pat.sub(new, t)
        total += c
    if errors:
        print("ОШИБКИ (файл НЕ записан):")
        for e in errors:
            print(" -", e)
        raise SystemExit(1)
    P.write_text(t, encoding="utf-8")
    print(f"OK: {total} замен в {len(WORDS)} словах")


if __name__ == "__main__":
    main()
