#!/usr/bin/env python3
"""Проход 4: буква ё в однозначных словах. Только папка проекта."""
from pathlib import Path
import re

P = Path("/home/v/projects/Красный хлеб/2015.52429.Red-Bread_djvu.ru.txt")

# слово -> (замена, ожидаемое число). Все проверены разведкой.
WORDS = {
    "еще": ("ещё", 119),
    "Еще": ("Ещё", 10),
    "ее": ("её", 211),
    "Ее": ("Её", 18),
    "нем": ("нём", 11),
    "моем": ("моём", 17),
    "твоем": ("твоём", 2),
    "своем": ("своём", 31),
    "свое": ("своё", 18),
    "черного": ("чёрного", 7),
    "черный": ("чёрный", 7),
    "черной": ("чёрной", 3),
    "черными": ("чёрными", 3),
    "черных": ("чёрных", 2),
    "черную": ("чёрную", 1),
    "черная": ("чёрная", 1),
    "Черная": ("Чёрная", 1),
    "желтый": ("жёлтый", 1),
    "желтые": ("жёлтые", 1),
    "зеленые": ("зелёные", 1),
    "теплое": ("тёплое", 1),
    "теплым": ("тёплым", 2),
    "теплой": ("тёплой", 1),
    "берет": ("берёт", 1),
    "идет": ("идёт", 6),
    "несет": ("несёт", 1),
    "пришел": ("пришёл", 11),
    "ушел": ("ушёл", 5),
    "нашел": ("нашёл", 2),
    "прошел": ("прошёл", 2),
    "придется": ("придётся", 12),
}

def main():
    t = P.read_text(encoding="utf-8")
    errors = []
    total = 0
    for old, (new, exp) in WORDS.items():
        pat = re.compile(r"\b" + re.escape(old) + r"\b")
        c = len(pat.findall(t))
        if c != exp:
            errors.append(f"ОЖИДАЛОСЬ {exp}, НАЙДЕНО {c}: {old!r}")
            continue
        t = pat.sub(new, t)
        total += c
    if errors:
        print("ОШИБКИ (файл НЕ записан):")
        for e in errors:
            print(" -", e)
        raise SystemExit(1)
    P.write_text(t, encoding="utf-8")
    print(f"OK: {total} замен в {len(WORDS)} словах")

if __name__ == "__main__":
    main()
