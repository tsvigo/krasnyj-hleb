#!/usr/bin/env python3
"""Проход 6: пропуски, склейки, ё-глаголы. Только папка проекта."""
from pathlib import Path
import re

P = Path("/home/v/projects/Красный хлеб/2015.52429.Red-Bread_djvu.ru.txt")
t = P.read_text(encoding="utf-8")

PAIRS = [
    ("всё на простой обещание молодого революционера",
     "всё на простое обещание молодого революционера", 1),
    ("Они видели, что случилось с...",
     "Они видели, что случилось с… [далее в скане пропуск]", 1),
    ("Я пошел домой с…\n\nСтарый друг, в его конюшне я и ночевал.",
     "Я пошёл домой со старым другом — ночевал в его конюшне.", 1),
    ("хуже могло быть наше \nжизнь в колхозе",
     "хуже могло быть наша \nжизнь в колхозе", 1),
    ("центром его прихода. Когда\n\n♦ Карикатуры",
     "центром его прихода.\n\n♦ Карикатуры", 1),
    ("мы стали посмешищем по всей округе. Бедная история, если",
     "мы стали посмешищем по всей округе. Бедная история, если… [далее в скане пропуск]", 1),
    ("готовились к \nзимовым посевам",
     "готовились к \nозимым посевам", 1),
    ("вклинилась ртушка с",
     "вклинилась бабушка с", 1),
    ("самому воспоминанию о \nлучшие времена,",
     "самому воспоминанию о \nлучших временах,", 1),
    ("на волнение от…",
     "на волнение минуты,", 1),
    ("построены ясли даже в…»",
     "построены ясли даже в этих деревнях, как во многих других вокруг?»", 1),
    ("И что же это за деревни и в этих-то деревнях, как во многих других вокруг? И для чего",
     "И для чего", 1),
    ("загнать все свои\n\nОвес и другие боялись",
     "загнать весь свой овёс, а другие боялись", 1),
]

YO_VERBS = {
    "пошел": ("пошёл", 9),  # 10-й съеден склейкой выше
    "подошел": ("подошёл", 10),
    "вошел": ("вошёл", 6),
    "перешел": ("перешёл", 1),
    "сошел": ("сошёл", 1),
    "обошел": ("обошёл", 1),
    "отошел": ("отошёл", 1),
    "произошел": ("произошёл", 1),
}

errors, n = [], 0
for old, new, exp in PAIRS:
    c = t.count(old)
    if c != exp:
        errors.append(f"ОЖИДАЛОСЬ {exp}, НАЙДЕНО {c}: {old[:70]!r}")
        continue
    t = t.replace(old, new)
    n += 1
for old, (new, exp) in YO_VERBS.items():
    pat = re.compile(r"\b" + re.escape(old) + r"\b")
    c = len(pat.findall(t))
    if c != exp:
        errors.append(f"ОЖИДАЛОСЬ {exp}, НАЙДЕНО {c}: {old!r}")
        continue
    t = pat.sub(new, t)
    n += c
if errors:
    print("ОШИБКИ (файл НЕ записан):")
    for e in errors:
        print(" -", e)
    raise SystemExit(1)
P.write_text(t, encoding="utf-8")
print(f"OK: {n} замен")
