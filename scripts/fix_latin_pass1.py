def main():
    t = P.read_text(encoding="utf-8")
    errors = []
    applied = 0
    for old, new, exp in PAIRS:
        c = t.count(old)
        if c != exp:
            errors.append(f"ОЖИДАЛОСЬ {exp}, НАЙДЕНО {c}: {old[:80]!r}")
            continue
        t = t.replace(old, new)
        applied += 1
    # одиночная строка 'R'
    lines = t.split("\n")
    r_idx = [i for i, l in enumerate(lines) if l.strip() == "R"]
    if len(r_idx) != 1:
        errors.append(f"строка 'R': ожидалась 1, найдено {len(r_idx)}")
    else:
        lines[r_idx[0]] = ""
        t = "\n".join(lines)
        applied += 1
    if errors:
        print("ОШИБКИ (файл НЕ записан):")
        for e in errors:
            print(" -", e)
        raise SystemExit(1)
    P.write_text(t, encoding="utf-8")
    print(f"OK: применено {applied} замен")

if __name__ == "__main__":
    main()
